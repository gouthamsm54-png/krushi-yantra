  t(key, lang = null) {
    const l = lang || this.currentLang || "hi";
    if (this.strings[l] && this.strings[l][key]) {
      return this.strings[l][key];
    }
    if (this.strings.en && this.strings.en[key]) {
      return this.strings.en[key];
    }
    return key;
  },

  setLanguage(lang) {
    if (!this.languages[lang]) return;
    this.currentLang = lang;
    try {
      localStorage.setItem("plantDrLang", lang);
    } catch (e) {
      // ignore
    }
  },

  initLanguage() {
    let saved = "hi";
    try {
      saved = localStorage.getItem("plantDrLang") || "hi";
    } catch (e) {
      saved = "hi";
    }
    this.currentLang = this.languages[saved] ? saved : "hi";
    return this.currentLang;
  }
